<?php

namespace App\Support;

use App\Models\CctvCamera;
use ZipArchive;

/**
 * Builds the setup files for the CCTV gateway (MediaMTX on the office PC). Camera
 * passwords are never known to Nepsus: the file has placeholders filled in on the PC.
 */
class CctvGateway
{
    public const MEDIAMTX_VERSION = 'v1.21.2';

    public const PASSWORD_PLACEHOLDER = 'PUT-CAMERA-PASSWORD-HERE';

    public static function mediamtxYml(): string
    {
        $app = CctvToken::issuer();
        // The site address from APP_URL, plus the one this file was downloaded from (www vs non-www).
        $origins = collect([$app, rtrim(url('/'), '/')])->unique()->map(fn ($o) => '"'.$o.'"')->join(', ');
        $cameras = CctvCamera::orderBy('position')->orderBy('id')->get();

        $paths = $cameras->map(function (CctvCamera $c) {
            $camera = 'rtsp://admin:'.self::PASSWORD_PLACEHOLDER.'@'.($c->camera_ip ?: 'CAMERA-IP').':554'.$c->rtsp_path;
            $head = ["  # {$c->name}".($c->location ? " ({$c->location})" : '').($c->enabled ? '' : ' - disabled in Nepsus'), "  {$c->stream_path}:"];

            return implode("\n", $c->transcode ? [...$head,
                '    # H.265 -> H.264 (720p) with ffmpeg.exe from this folder, only while someone is watching.',
                '    runOnDemand: '.self::ffmpeg($camera),
                '    runOnDemandRestart: true',
                '    runOnDemandStartTimeout: 20s',
                '    runOnDemandCloseAfter: 15s',
            ] : [...$head,
                '    source: '.$camera,
                '    rtspTransport: tcp',
                '    sourceOnDemand: true           # only connect to the camera while someone is watching',
                '    sourceOnDemandStartTimeout: 15s',
                '    sourceOnDemandCloseAfter: 15s',
            ]);
        })->join("\n\n");

        // ffmpeg hands the converted video to a local RTSP server that only this PC can reach,
        // so publishing to it needs no token. Viewers always need one.
        $rtsp = $cameras->contains('transcode', true)
            ? "rtsp: true\nrtspAddress: 127.0.0.1:8554\nrtspTransports: [tcp]\nauthJWTExclude: [{action: publish}]"
            : 'rtsp: false';

        $generated = now()->format('Y-m-d H:i');
        $version = self::MEDIAMTX_VERSION;

        return <<<YML
            # Nepsus CCTV gateway - MediaMTX {$version} configuration.
            # Generated by Nepsus on {$generated}.
            #
            # 1. Replace every PUT-CAMERA-PASSWORD-HERE below with that camera's password
            #    (EZVIZ: the verification code on the camera label). Keep this file private.
            #    Special characters must be written as codes: @ = %40  : = %3A  # = %23  / = %2F  % = %25
            #    e.g. password "@Office5" is written %40Office5
            # 2. Video is only served to people signed in to Nepsus with CCTV access:
            #    every request needs a short-lived token signed by Nepsus.

            logLevel: info

            # Viewing tokens are checked with the public key published by Nepsus.
            authMethod: jwt
            authJWTJWKS: {$app}/api/cctv/jwks
            authJWTClaimKey: mediamtx_permissions
            authJWTIssuer: {$app}

            # Only HLS is needed. Everything else stays off.
            api: false
            metrics: false
            pprof: false
            playback: false
            {$rtsp}
            rtmp: false
            srt: false
            webrtc: false
            moq: false

            hls: true
            # Only this PC can reach the gateway directly; Tailscale serve publishes it privately over HTTPS.
            hlsAddress: 127.0.0.1:8888
            hlsAllowOrigins: [{$origins}]
            hlsVariant: lowLatency
            hlsSegmentCount: 7
            hlsMuxerCloseAfter: 30s

            paths:
            {$paths}
            YML;
    }

    /** ffmpeg command that reads the camera and publishes H.264 to the gateway's local RTSP server. */
    private static function ffmpeg(string $camera): string
    {
        return 'ffmpeg.exe -hide_banner -loglevel error -rtsp_transport tcp -i '.$camera
            .' -map 0:v:0 -map 0:a:0? -c:v libx264 -preset veryfast -tune zerolatency -vf scale=-2:720 -g 50 -bf 0'
            .' -c:a aac -b:a 64k -ar 44100 -f rtsp -rtsp_transport tcp rtsp://127.0.0.1:$RTSP_PORT/$MTX_PATH';
    }

    /** Zip with mediamtx.yml, start and auto-start scripts and a README. Returns the temp path. */
    public static function zip(): string
    {
        $path = tempnam(sys_get_temp_dir(), 'cctv');
        $zip = new ZipArchive;
        $zip->open($path, ZipArchive::OVERWRITE);

        $zip->addFromString('mediamtx.yml', self::mediamtxYml()."\n");
        $zip->addFromString('start-gateway.bat', self::crlf(<<<'BAT'
            @echo off
            rem Starts the Nepsus CCTV gateway in this window (close the window to stop it).
            cd /d "%~dp0"
            if not exist mediamtx.exe (
              echo mediamtx.exe is missing. Download MediaMTX for Windows and put mediamtx.exe in this folder.
              pause
              exit /b 1
            )
            findstr /c:"runOnDemand: ffmpeg.exe" mediamtx.yml >nul && if not exist ffmpeg.exe (
              echo ffmpeg.exe is missing. It converts the camera video so browsers can play it.
              echo Download FFmpeg for Windows and put ffmpeg.exe in this folder. See README.txt.
              pause
              exit /b 1
            )
            mediamtx.exe mediamtx.yml
            pause
            BAT));
        $zip->addFromString('gateway-service.bat', self::crlf(<<<'BAT'
            @echo off
            rem Used by the Windows startup task: runs the gateway from this folder (so it finds ffmpeg.exe).
            cd /d "%~dp0"
            mediamtx.exe mediamtx.yml
            BAT));
        $zip->addFromString('install-autostart.bat', self::crlf(<<<'BAT'
            @echo off
            rem Starts the gateway in the background every time Windows starts (run as administrator).
            cd /d "%~dp0"
            schtasks /Create /TN "Nepsus CCTV Gateway" /TR "\"%~dp0gateway-service.bat\"" /SC ONSTART /RU SYSTEM /RL HIGHEST /F
            schtasks /Run /TN "Nepsus CCTV Gateway"
            echo The CCTV gateway now starts with Windows.
            pause
            BAT));
        $zip->addFromString('remove-autostart.bat', self::crlf(<<<'BAT'
            @echo off
            rem Stops the gateway from starting with Windows (run as administrator).
            schtasks /End /TN "Nepsus CCTV Gateway"
            schtasks /Delete /TN "Nepsus CCTV Gateway" /F
            pause
            BAT));
        $zip->addFromString('README.txt', self::crlf(self::readme()));
        $zip->close();

        return $path;
    }

    private static function readme(): string
    {
        $version = self::MEDIAMTX_VERSION;
        $app = CctvToken::issuer();

        return <<<TXT
            NEPSUS CCTV GATEWAY - SETUP ON THE OFFICE PC
            ============================================

            How it works
              Camera (RTSP, office network) -> MediaMTX on this PC -> HLS video -> your browser.
              Nepsus ({$app}) only decides who may watch and signs a short-lived token.
              Video never goes through Hostinger, and camera passwords never leave this PC.
              When this PC is off, Nepsus shows "Camera unavailable".

            1. Install MediaMTX
               Download mediamtx_{$version}_windows_amd64.zip from
               https://github.com/bluenviron/mediamtx/releases
               and copy mediamtx.exe into this folder (keep the mediamtx.yml from Nepsus).

               Also put ffmpeg.exe in this folder (needed when "Convert video" is on for a camera,
               which EZVIZ H.265 cameras such as the H6c need). Download the Windows "essentials"
               build from https://www.gyan.dev/ffmpeg/builds/ and copy binfmpeg.exe here.

            2. Add the camera passwords
               Open mediamtx.yml in Notepad and replace every PUT-CAMERA-PASSWORD-HERE with
               the camera password (EZVIZ: the verification code on the camera label).
               Use the same RTSP address that works in VLC.
               Special characters must be written as codes:
                 @ = %40   : = %3A   # = %23   / = %2F   % = %25   (e.g. @Office5 -> %40Office5)

            3. Test it
               Double-click start-gateway.bat. Leave the window open.

            4. Watching inside the office (Nepsus running on this PC over http)
               In Nepsus: CCTV Monitoring -> Cameras -> Gateway address = http://127.0.0.1:8888

            5. Watching from anywhere, with Nepsus on Hostinger (HTTPS)
               A website on https:// may not load video from http:// (browser "mixed content"),
               and the gateway must not be opened to the public internet. Use Tailscale (free
               Personal plan at the time of writing - check its current limits):
                 a. Install Tailscale on this PC and sign in. In the Tailscale admin console turn
                    on MagicDNS and HTTPS certificates.
                 b. Open Command Prompt and run:  tailscale serve --bg 8888
                    It prints an address like https://office-pc.your-tailnet.ts.net
                 c. In Nepsus: CCTV Monitoring -> Cameras -> Gateway address = that https address.
                 d. Every phone or laptop that should watch installs Tailscale and joins the same
                    tailnet (or you share this PC with them from the Tailscale console).
               Only devices in your tailnet can reach the gateway, and they still need a Nepsus
               login with CCTV access for every camera.

            6. Start with Windows
               Right-click install-autostart.bat -> Run as administrator.
               (remove-autostart.bat undoes it.)

            Changed cameras in Nepsus? Download this setup again and copy the new mediamtx.yml
            (keep your passwords), then restart the gateway.
            TXT;
    }

    private static function crlf(string $text): string
    {
        return str_replace(["\r\n", "\n"], ["\n", "\r\n"], $text);
    }
}
